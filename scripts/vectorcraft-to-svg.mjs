// Converts the owner's logo drawing (Obsen.vectorcraft) into the SVG markup the app shows
// in the vault chooser and the title bar. Re-run after the drawing changes.
// Usage: node scripts/vectorcraft-to-svg.mjs [input] [output.ts]
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const input = path.resolve(process.argv[2] ?? path.join(root, "Obsen.vectorcraft"));
const output = path.resolve(process.argv[3] ?? path.join(root, "src/renderer/logo.ts"));
const { document: doc } = JSON.parse(fs.readFileSync(input, "utf8"));

const n = value => String(Math.round(value * 100) / 100);
const hex = (r, g, b) => "#" + [r, g, b].map(v => Math.round(Math.max(0, Math.min(1, v)) * 255).toString(16).padStart(2, "0")).join("");
function color(c) {
  if (c.model === "rgb") return hex(c.r, c.g, c.b);
  if (c.model === "gray") return hex(1 - c.k, 1 - c.k, 1 - c.k);
  if (c.model === "cmyk") return hex((1 - c.c) * (1 - c.k), (1 - c.m) * (1 - c.k), (1 - c.y) * (1 - c.k));
  throw new Error("Unsupported colour model " + c.model);
}
function subpath({ anchors, closed }) {
  let d = `M${n(anchors[0].p[0])} ${n(anchors[0].p[1])}`;
  const count = closed ? anchors.length : anchors.length - 1;
  for (let i = 0; i < count; i++) {
    const a = anchors[i], b = anchors[(i + 1) % anchors.length];
    if (!a.out && !b.in) d += `L${n(b.p[0])} ${n(b.p[1])}`;
    else { const c1 = a.out ?? a.p, c2 = b.in ?? b.p; d += `C${n(c1[0])} ${n(c1[1])} ${n(c2[0])} ${n(c2[1])} ${n(b.p[0])} ${n(b.p[1])}`; }
  }
  return d + (closed ? "Z" : "");
}
const pathData = node => node.kind.type === "path" ? node.kind.path.subpaths.map(subpath).join("")
  : node.kind.type === "compound" ? node.kind.children.map(pathData).join("") : "";
function paint(appearance) {
  const items = appearance?.items ?? [];
  const fill = items.find(item => item.kind === "fill" && item.paint.type === "solid");
  const stroke = items.find(item => item.kind === "stroke" && item.paint.type === "solid");
  return ` fill="${fill ? color(fill.paint.color) : "none"}"` + (stroke ? ` stroke="${color(stroke.paint.color)}" stroke-width="${n(stroke.width ?? 1)}"` : "");
}
function render(node) {
  const { type } = node.kind;
  if (type === "group" || type === "layer") return node.kind.children.map(render).join("");
  if (type === "path") return `<path d="${pathData(node)}"${paint(node.appearance)}/>`;
  if (type === "compound") return `<path fill-rule="evenodd" d="${pathData(node)}"${paint(node.appearance)}/>`;
  throw new Error("Unsupported node type " + type);
}

// The outline shown in the title bar until the pointer is over it.
function outline(node) {
  const { type } = node.kind;
  if (type === "group" || type === "layer") return node.kind.children.map(outline).join("");
  return `<path d="${pathData(node)}"/>`;
}

const { rect } = doc.artboards[0];
const width = rect.x1 - rect.x0, height = rect.y1 - rect.y0;
const viewBox = `${n(rect.x0)} ${n(rect.y0)} ${n(width)} ${n(height)}`;
const full = doc.layers.map(render).join("");
const wireframe = `<g fill="none" stroke="currentColor" stroke-width="${n(width / 18)}" stroke-linejoin="round">${doc.layers.map(outline).join("")}</g>`;
const source = [
  `// Generated by scripts/vectorcraft-to-svg.mjs from ${path.basename(input)}; do not edit by hand.`,
  `export const LOGO_VIEW_BOX = ${JSON.stringify(viewBox)};`,
  `export const LOGO_FULL = ${JSON.stringify(full)};`,
  `export const LOGO_WIREFRAME = ${JSON.stringify(wireframe)};`,
  "/** The logo as SVG markup; the wireframe is the title bar's resting state. */",
  'export const logoSvg = (size: number, kind: "full" | "wireframe" = "full") =>',
  '  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${LOGO_VIEW_BOX}" width="${size}" height="${size}" class="logo-${kind}" overflow="visible">${kind === "wireframe" ? LOGO_WIREFRAME : LOGO_FULL}</svg>`;',
  "",
].join("\n");
fs.writeFileSync(output, source);
console.log(`${path.relative(root, output)}: ${source.length} bytes`);
