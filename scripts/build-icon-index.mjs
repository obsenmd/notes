// Compile replaceable custom SVG files into the synchronous icon registry.
import fs from 'node:fs/promises';
import path from 'node:path';

const directory = path.resolve(import.meta.dirname, '../assets/icons');
const names = JSON.parse(await fs.readFile(path.join(directory, 'manifest.json'), 'utf8'));
if (!Array.isArray(names) || names.length !== 44 || new Set(names).size !== names.length) throw new Error('Expected 44 distinct custom icon names');
const icons = {};
for (const name of names) {
  if (typeof name !== 'string' || !/^[a-z0-9-]+$/.test(name)) throw new Error(`Invalid icon name: ${name}`);
  const source = (await fs.readFile(path.join(directory, `${name}.svg`), 'utf8')).trim();
  if (!/^<svg\b[^>]*>[\s\S]*<\/svg>$/.test(source)) throw new Error(`Invalid SVG icon: ${name}`);
  icons[name] = source;
}
await fs.writeFile(path.join(directory, 'index.ts'), [
  '// Generated by scripts/build-icon-index.mjs from the replaceable SVG files.',
  `export const customIcons: Record<string, string> = ${JSON.stringify(icons, null, 1)};`,
  '',
].join('\n'));
console.log(`Indexed ${names.length} custom SVG icons.`);
