// Generates the reference Lucide table and replaceable custom SVG files.
// Usage: node scripts/build-icons.mjs <path-to-reference-app.js>
import fs from 'node:fs/promises';

const [bundle] = process.argv.slice(2);
if (!bundle) throw new Error('Usage: node scripts/build-icons.mjs <path-to-reference-app.js>');
const source = await fs.readFile(bundle, 'utf8');
const BACKSLASH = String.fromCharCode(92);

/** Returns the object literal that encloses `marker`. */
function objectAround(marker) {
  const at = source.indexOf(marker);
  if (at < 0) throw new Error(`Icon table marker not found: ${marker}`);
  let depth = 0, start = -1;
  for (let i = at; i >= 0; i--) {
    if (source[i] === '}') depth++;
    else if (source[i] === '{') { if (depth === 0) { start = i; break; } depth--; }
  }
  let end = start, open = 0, quote = null;
  for (; end < source.length; end++) {
    const char = source[end];
    if (quote) { if (char === BACKSLASH) end++; else if (char === quote) quote = null; continue; }
    if (char === '"' || char === "'" || char === '`') quote = char;
    else if (char === '{') open++;
    else if (char === '}' && --open === 0) break;
  }
  return new Function(`return ${source.slice(start, end + 1)}`)();
}

const attributes = values => Object.entries(values).map(([name, value]) => ` ${name}="${String(value).replace(/"/g, '&quot;')}"`).join('');
// Shape tuples: 0 line, 1 circle, 2 polyline, 3 polygon, 4 ellipse, 5 rect, 6 path.
function shape(entry) {
  const [type, ...rest] = entry;
  if (type === 0) return `<line${attributes({ x1: rest[0], y1: rest[1], x2: rest[2], y2: rest[3] })}/>`;
  if (type === 1) return `<circle${attributes({ cx: rest[0], cy: rest[1], r: rest[2], ...(rest[3] ? { fill: 'currentColor' } : {}) })}/>`;
  if (type === 2) return `<polyline${attributes({ points: rest[0] })}/>`;
  if (type === 3) return `<polygon${attributes({ points: rest[0] })}/>`;
  if (type === 4) return `<ellipse${attributes({ cx: rest[0], cy: rest[1], rx: rest[2], ry: rest[3] })}/>`;
  if (type === 5) return `<rect${attributes({ x: rest[0], y: rest[1], width: rest[2], height: rest[3], ...(rest[4] ? { rx: rest[4] } : {}), ...(rest[5] ? { ry: rest[5] } : {}), ...(rest[6] ? { transform: rest[6] } : {}) })}/>`;
  if (type === 6) return `<path${attributes({ d: rest[0], ...(rest[1] ? { fill: 'currentColor' } : {}) })}/>`;
  throw new Error(`Unknown icon shape type ${type}`);
}

const lucide = objectAround('"zoom-out":[[1,11,11,8]');
const aliases = objectAround('"create-new":"edit"');
const custom = objectAround('"right-triangle":' + "'<path");
const lucideIcons = Object.fromEntries(Object.entries(lucide).map(([id, shapes]) => [id, shapes.map(shape).join('')]));

await fs.writeFile('assets/obsidian/lucide-icons.ts', [
  '// Generated by scripts/build-icons.mjs. Values are SVG bodies for a 24x24 stroked viewBox.',
  `export const lucideIcons: Record<string, string> = ${JSON.stringify(lucideIcons, null, 1)};`,
  '/** Legacy icon ids mapped to their lucide replacement. */',
  `export const iconAliases: Record<string, string> = ${JSON.stringify(aliases, null, 1)};`,
  '',
].join('\n'));
const iconDirectory = 'assets/icons';
await fs.mkdir(iconDirectory, { recursive: true });
const svgAttributes = 'xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
for (const [name, body] of Object.entries(custom)) {
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`Invalid custom icon name: ${name}`);
  await fs.writeFile(`${iconDirectory}/${name}.svg`, `<svg ${svgAttributes}>${body}</svg>\n`);
}
await fs.writeFile(`${iconDirectory}/manifest.json`, JSON.stringify(Object.keys(custom), null, 2) + '\n');
await import('./build-icon-index.mjs');
console.log(`Wrote ${Object.keys(lucideIcons).length} lucide icons, ${Object.keys(aliases).length} aliases, ${Object.keys(custom).length} custom icons.`);
