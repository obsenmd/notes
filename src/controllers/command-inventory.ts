/** Localized command name in the reference "Prefix: name" form. */
export function commandName(definition: CommandDefinition): string {
  const values = { ...definition.values, ...Object.fromEntries(Object.entries(definition.valueKeys ?? {}).map(([name, key]) => [name, t(key)])) };
  let name = definition.nameKey ? t(definition.nameKey, values) : definition.name ?? definition.id;
  if (definition.wrapKey) name = t(definition.wrapKey, { command: name });
  return definition.prefixKey ? `${t(definition.prefixKey)}: ${name}` : name;
}
